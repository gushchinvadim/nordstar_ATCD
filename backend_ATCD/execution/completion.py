"""Effective training date is separate from the time of the methodist's action."""
import json
from django.db.models import Max
from rest_framework.exceptions import ValidationError
from .local_time import group_timezone, group_today
from .models import Assessment, ComplianceLog, Enrollment, ScheduleItem


def completion_context(group):
    planned = ScheduleItem.objects.filter(group=group).aggregate(day=Max('date'))['day'] or group.end_date
    last_lesson = ScheduleItem.objects.filter(group=group, is_completed=True).aggregate(day=Max('date'))['day']
    last_assessment = Assessment.objects.filter(enrollment__group=group).aggregate(day=Max('assessment_date'))['day']
    dates = [d for d in (group.start_date, last_lesson, last_assessment) if d]
    minimum = max(dates) if dates else group_today(group)
    previous = Enrollment.objects.filter(group=group, status='completed').aggregate(day=Max('completed_at'))['day']
    decision = ComplianceLog.objects.filter(group=group, action_type='methodist_corrected',
        notes__contains='"operation": "enrollments_completed"').order_by('-timestamp', '-pk').first()
    decided_date, decided_reason = None, ''
    if decision:
        try:
            from datetime import date
            details = json.loads(decision.notes)
            decided_date = date.fromisoformat(details['completion_date'])
            decided_reason = details.get('reason', '')
        except (ValueError, KeyError, TypeError):
            pass
    suggested = group.actual_completion_date or decided_date or planned or last_assessment or previous or group_today(group)
    return {
        'planned_date': planned,
        'completion_date': suggested,
        'completion_reason': decided_reason,
        'minimum_date': minimum,
        'maximum_date': group_today(group),
        'timezone': str(group_timezone(group)),
        'closed': group.status in ('completed', 'archived'),
    }


def choose_completion_date(group, data):
    from rest_framework import serializers
    context = completion_context(group)
    raw = data.get('completion_date')
    selected = serializers.DateField().run_validation(raw) if raw is not None else context['completion_date']
    reason = str(data.get('completion_reason') or '').strip()
    if group.status in ('completed', 'archived') and group.actual_completion_date:
        if selected != group.actual_completion_date:
            raise ValidationError({'error': 'Группа уже закрыта. Изменение даты требует отдельной процедуры исправления документов.'})
        return selected, reason
    if selected < context['minimum_date']:
        raise ValidationError({'error': 'Дата окончания не может быть раньше начала обучения, проведённых занятий или выставленных оценок.'})
    if selected > context['maximum_date']:
        raise ValidationError({'error': 'Дата окончания не может быть в будущем по местному времени группы.'})
    baseline = context['planned_date'] or context['completion_date']
    if selected != baseline and not reason and selected != group.actual_completion_date:
        raise ValidationError({'error': 'Укажите причину изменения плановой даты окончания.'})
    return selected, reason


def log_completion_date(group, user, selected, reason, phase):
    # timestamp is generated by the server at the real time of the action.
    ComplianceLog.objects.create(
        group=group, staff=getattr(user, 'staff', None), action_type='methodist_corrected',
        notes=json.dumps({'operation': phase, 'completion_date': selected.isoformat(),
            'planned_date': str(completion_context(group)['planned_date'] or ''),
            'reason': reason, 'user_id': user.pk, 'username': user.get_username()}, ensure_ascii=False),
    )
